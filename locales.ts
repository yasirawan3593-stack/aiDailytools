export function getTranslation(lang: LanguageCode, key: string): string {
  const dict = translations[lang] || translations.en;
  if (key === 'credits') return lang === 'ur' ? 'کریڈٹس' : lang === 'hi' ? 'क्रेडिट' : lang === 'ar' ? 'نقاط' : 'Credits';
  if (key === 'searchPlaceholder') return dict.searchTools || 'Search AI tools, writers, translators...';
  return (dict as any)[key] || (translations.en as any)[key] || key;
}

